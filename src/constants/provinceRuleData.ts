export function buildProvinceYearCategoryType(
  rules: ProvinceCategoryBatchRule[],
): Record<string, Record<string, string>> {
  return rules.reduce<Record<string, Record<string, string>>>((acc, rule) => {
    const year = String(rule.year || '').trim()
    const province = String(rule.province || '').trim()
    const categoryType = String(rule.categoryType || '').trim()

    if (!year || !province || !categoryType) return acc

    if (!acc[year]) acc[year] = {}
    acc[year][province] = categoryType

    return acc
  }, {})
}

export function buildProvinceCurrentBatchDictByYear(
  rules: ProvinceCategoryBatchRule[],
): Record<string, Record<string, string[]>> {
  return rules.reduce<Record<string, Record<string, string[]>>>((acc, rule) => {
    const year = String(rule.year || '').trim()
    const province = String(rule.province || '').trim()
    const batches = Array.from(
      new Set((rule.batches || []).map((item) => String(item || '').trim()).filter(Boolean)),
    )

    if (!year || !province || batches.length === 0) return acc

    if (!acc[year]) acc[year] = {}
    acc[year][province] = batches

    return acc
  }, {})
}
