function t(value: unknown): string {
  if (value === null || value === undefined) return ''
  return String(value).trim()
}

function normalizeText(value: unknown): string {
  return t(value)
    .replace(/\s+/g, '')
    .replace(/[（）()\[\]【】]/g, '')
    .replace(/[\-—–_]/g, '')
}

function includesAny(text: string, keywords: string[]): boolean {
  return keywords.some((keyword) => text.includes(keyword))
}

function getProvinceConfig(province: unknown): ControlLineConfig | undefined {
  const text = t(province).replace(/省|市|自治区|壮族|回族|维吾尔/g, '')
  return CONTROL_LINE_2025.find((item) => item.province === text || item.province === t(province))
}

function scoreCategory(option: string, categoryText: string): number {
  const optionText = normalizeText(option)

  if (!categoryText) return 0
  if (optionText === categoryText) return 100
  if (categoryText.includes(optionText) || optionText.includes(categoryText)) return 90

  if (categoryText.includes('物理') || categoryText === '物') {
    return optionText.includes('物理') ? 95 : 0
  }
  if (categoryText.includes('历史') || categoryText === '历') {
    return optionText.includes('历史') ? 95 : 0
  }
  if (includesAny(categoryText, ['理工', '理科'])) {
    return optionText.includes('理科') ? 95 : 0
  }
  if (includesAny(categoryText, ['文史', '文科'])) {
    return optionText.includes('文科') ? 95 : 0
  }
  if (includesAny(categoryText, ['综合', '普通'])) {
    return optionText.includes('综合') ? 95 : 0
  }

  return 0
}

export function resolveControlLineCategory(province: unknown, enrollmentCategory: unknown): string {
  const category = t(enrollmentCategory)
  const config = getProvinceConfig(province)
  if (!config) return category

  const normalizedCategory = normalizeText(category)
  const best = config.categories
    .map((option) => ({ option, score: scoreCategory(option, normalizedCategory) }))
    .sort((a, b) => b.score - a.score)[0]

  if (best && best.score > 0) return best.option
  return category
}

function getBatchKeywordScore(option: string, batch: string): number {
  const optionText = normalizeText(option)
  const batchText = normalizeText(batch)
  let score = 0

  if (includesAny(batchText, ['特殊', '特招']) && optionText.includes('特殊类型招生控制线')) score += 120

  if (batchText.includes('提前') && optionText.includes('提前')) score += 50
  if (batchText.includes('国家专项') && optionText.includes('国家专项')) score += 60
  if (batchText.includes('地方专项') && optionText.includes('地方专项')) score += 60

  if (batchText.includes('艺术') && optionText.includes('艺术')) score += 45
  if (batchText.includes('体育') && optionText.includes('体育')) score += 45

  if (batchText.includes('专科') || batchText.includes('高职')) {
    if (optionText.includes('专科') || optionText.includes('高职')) score += 35
    if (batchText.includes('提前') === optionText.includes('提前')) score += 10
  }

  if (batchText.includes('本科')) {
    if (optionText.includes('本科')) score += 30
    if (includesAny(batchText, ['一批', '一本', '第一批']) && includesAny(optionText, ['一批', '一段'])) score += 35
    if (includesAny(batchText, ['二批', '二本', '第二批']) && includesAny(optionText, ['二批', '二段'])) score += 35
    if (includesAny(batchText, ['三批', '三本', '第三批']) && optionText.includes('三批')) score += 35
    if (batchText.includes('本科批') && optionText.includes('本科批')) score += 35
  }

  if (batchText.includes('一段') && optionText.includes('一段')) score += 35
  if (batchText.includes('二段') && optionText.includes('二段')) score += 35

  return score
}

function scoreBatch(option: string, enrollmentBatch: string, enrollmentCategory: string): number {
  const optionText = normalizeText(option)
  const batchText = normalizeText(enrollmentBatch)
  const categoryText = normalizeText(enrollmentCategory)

  if (!batchText) return 0
  if (optionText === batchText) return 1000

  let score = getBatchKeywordScore(optionText, batchText)

  if (batchText.includes(optionText)) score += 300 + optionText.length
  if (optionText.includes(batchText)) score += 220 + batchText.length

  if (categoryText.includes('艺术') && optionText.includes('艺术')) score += 20
  if (categoryText.includes('体育') && optionText.includes('体育')) score += 20

  return score
}

export function resolveControlLineBatch(
  province: unknown,
  enrollmentBatch: unknown,
  enrollmentCategory: unknown = ''
): string {
  const batch = t(enrollmentBatch)
  const config = getProvinceConfig(province)
  if (!config) return batch

  const best = config.batches
    .map((option) => ({
      option,
      score: scoreBatch(option, batch, t(enrollmentCategory)),
    }))
    .sort((a, b) => b.score - a.score)[0]

  if (best && best.score > 0) return best.option
  return batch
}

export function resolveControlLine(
  province: string,
  enrollmentCategory: string,
  enrollmentBatch: string,
  year?: string | number,
): {
  category: string
  batch: string
} {
  const yearText = String(year ?? '').trim()

  // 这个省控线配置只适用于 2025 年。
  // 年份为空、2024、2026 等其他年份，都禁止使用。
  if (yearText !== '2025') {
    return {
      category: '',
      batch: '',
    }
  }

  return {
    category: resolveControlLineCategory(province, enrollmentCategory),
    batch: resolveControlLineBatch(province, enrollmentBatch, enrollmentCategory),
  }
}
